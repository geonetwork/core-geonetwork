package org.fao.geonet.api.records.attachments;

import org.fao.geonet.services.AbstractServiceIntegrationTest;
import org.junit.Before;
import org.junit.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.web.context.WebApplicationContext;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

public class LegacyAttachmentLinksControllerTest extends AbstractServiceIntegrationTest {

    @Autowired
    private WebApplicationContext wac;

    private MockMvc mockMvc;

    @Before
    public void setUp() {
        mockMvc = MockMvcBuilders.webAppContextSetup(wac).build();
    }

    @Test
    public void redirectsToAttachment() throws Exception {
        for (String service : new String[]{"file.disclaimer", "resources.get.archive"}) {
            mockMvc.perform(get("/srv/eng/" + service)
                    .param("uuid", "abc-123").param("fname", "my data.zip").param("access", "private"))
                .andExpect(status().isMovedPermanently())
                .andExpect(header().string("Location", "/srv/api/records/abc-123/attachments/my%20data.zip"));
        }
    }

    @Test
    public void unknownRecord() throws Exception {
        mockMvc.perform(get("/srv/eng/file.disclaimer").param("fname", "data.zip"))
            .andExpect(status().isNotFound());
    }
}
